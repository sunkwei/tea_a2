# scripts/install-bus-autostart.ps1 -- start the message platform's pieces at logon.
#
# Windows has no user-scoped `systemctl --user enable`; the closest equivalent is a
# Task Scheduler task with a logon trigger and an InteractiveToken principal (the
# same approach as scripts/install-autostart.ps1, which does this for the agent).
#
# The four pieces (docs/message-platform.md, docs/message-platform-design.md §11):
#
#   bus       sched\bus_server.py    publish / subscribe (127.0.0.1:8299)
#   bus_pump  sched\bus_pump.py      queue events -> the platform
#   router    sched\router.py        --bus <BusUrl>   (speech + heartbeat)
#   watchdog  sched\watchdog.py      --bus <BusUrl>   (heartbeats -> alerts:
#                                    router_missing, pump_missing, bus_missing)
#
#   pwsh -File scripts/install-bus-autostart.ps1 -All              # register all four
#   pwsh -File scripts/install-bus-autostart.ps1 -Name bus,router  # just these
#   pwsh -File scripts/install-bus-autostart.ps1 -All -Start       # register + run now
#   pwsh -File scripts/install-bus-autostart.ps1 -Status           # what is registered?
#   pwsh -File scripts/install-bus-autostart.ps1 -Uninstall -All   # remove them
#   pwsh -File scripts/install-bus-autostart.ps1 -All -DryRun      # print the plan
#
# Each task runs a generated .cmd through a .vbs shim: the .cmd restarts the
# program when it exits non-zero, and the shim keeps the console window hidden.
# Logs go to %USERPROFILE%\.tea_agent\logs\<name>.log.
#
# ASCII only on purpose: Windows PowerShell 5.1 reads a UTF-8 file without a BOM
# as ANSI, and non-ASCII comments turn into mojibake (see tea_a2_agent.md).

[CmdletBinding()]
param(
    [string[]]$Name = @(),
    [switch]$All,
    [string]$Python = "",
    [string]$Repo = "",
    [string]$BusUrl = "http://127.0.0.1:8299",
    [string]$LauncherDir = "",
    [switch]$Start,
    [switch]$Status,
    [switch]$Uninstall,
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'

$root = if ($Repo) { [IO.Path]::GetFullPath($Repo) } else { Split-Path -Parent $PSScriptRoot }
if (-not (Test-Path (Join-Path $root 'sched\bus_server.py'))) {
    throw "not a tea_a2 checkout (sched\bus_server.py missing): $root"
}

if (-not $Python) {
    $found = Get-Command python -ErrorAction SilentlyContinue
    if (-not $found) { $found = Get-Command python3 -ErrorAction SilentlyContinue }
    if (-not $found) { throw "no python on PATH; pass -Python <path>" }
    $Python = $found.Source
}

$components = [ordered]@{
    bus      = @{ Script = 'sched\bus_server.py'; Args = @() }
    bus_pump = @{ Script = 'sched\bus_pump.py'; Args = @() }
    router   = @{ Script = 'sched\router.py'; Args = @('--bus', $BusUrl) }
    watchdog = @{ Script = 'sched\watchdog.py'; Args = @('--bus', $BusUrl, '--expect-heartbeat', 'a2/heartbeat/router', '--expect-heartbeat', 'a2/heartbeat/pump') }
}

function Get-LauncherDir {
    if ($LauncherDir) { return [IO.Path]::GetFullPath($LauncherDir) }
    $homeDir = if ($env:TEA_AGENT_HOME) { $env:TEA_AGENT_HOME } else { Join-Path $env:USERPROFILE '.tea_agent' }
    return [IO.Path]::GetFullPath((Join-Path $homeDir 'autostart'))
}

function Get-TaskOf {
    param([string]$TaskName)
    try { return Get-ScheduledTask -TaskName $TaskName -ErrorAction Stop } catch { return $null }
}

function Get-Names {
    if ($All -or ($Name.Count -eq 0 -and ($Status -or $Uninstall))) {
        return @($components.Keys)
    }
    if ($Name.Count -eq 0) {
        throw "say which ones: -Name bus,bus_pump,router,watchdog (or -All)"
    }
    foreach ($n in $Name) {
        if (-not $components.Contains($n)) {
            throw "unknown component '$n' (known: $($components.Keys -join ', '))"
        }
    }
    return @($Name)
}

function TaskNameOf {
    param([string]$Component)
    return "tea_a2_$Component"
}

function Make-Cmd {
    param([string]$Component, [string]$LauncherDirPath)
    $spec = $components[$Component]
    $script = Join-Path $root $spec.Script
    $log = Join-Path (Join-Path (Split-Path -Parent $LauncherDirPath) 'logs') ("$Component.log")
    $argLine = ($spec.Args | ForEach-Object { '"' + $_ + '"' }) -join ' '
    $cmdPath = Join-Path $LauncherDirPath ("start-$Component.cmd")
    $lines = @(
        '@echo off',
        'rem generated by scripts/install-bus-autostart.ps1',
        ('cd /d "' + $root + '"'),
        ':loop',
        ('"' + $Python + '" "' + $script + '" ' + $argLine + ' >> "' + $log + '" 2>&1'),
        'if %errorlevel% equ 0 exit /b 0',
        'timeout /t 5 /nobreak >nul',
        'goto loop'
    )
    Set-Content -Path $cmdPath -Value ($lines -join "`r`n") -Encoding ASCII
    return $cmdPath
}

function Make-Vbs {
    param([string]$Component, [string]$CmdPath, [string]$LauncherDirPath)
    $vbsPath = Join-Path $LauncherDirPath ("start-$Component.vbs")
    $lines = @(
        "' generated by scripts/install-bus-autostart.ps1",
        'Set shell = CreateObject("WScript.Shell")',
        ('shell.Run """' + $CmdPath + '""", 0, True')
    )
    Set-Content -Path $vbsPath -Value ($lines -join "`r`n") -Encoding ASCII
    return $vbsPath
}

function TaskXml {
    param([string]$Component, [string]$VbsPath)
    $user = [Security.Principal.WindowsIdentity]::GetCurrent().Name
    $taskName = TaskNameOf $Component
    return @"
<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>tea_a2 $Component (generated by scripts/install-bus-autostart.ps1).</Description>
  </RegistrationInfo>
  <Triggers>
    <LogonTrigger>
      <Enabled>true</Enabled>
      <UserId>$([Security.SecurityElement]::Escape($user))</UserId>
      <Delay>PT5S</Delay>
    </LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>$([Security.SecurityElement]::Escape($user))</UserId>
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <IdleSettings>
      <StopOnIdleEnd>false</StopOnIdleEnd>
      <RestartOnIdle>false</RestartOnIdle>
    </IdleSettings>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <RunOnlyIfIdle>false</RunOnlyIfIdle>
    <WakeToRun>false</WakeToRun>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Priority>7</Priority>
    <RestartOnFailure>
      <Interval>PT1M</Interval>
      <Count>999</Count>
    </RestartOnFailure>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>$([Security.SecurityElement]::Escape((Join-Path $env:WINDIR 'System32\wscript.exe')))</Command>
      <Arguments>"$([Security.SecurityElement]::Escape($VbsPath))"</Arguments>
      <WorkingDirectory>$([Security.SecurityElement]::Escape($root))</WorkingDirectory>
    </Exec>
  </Actions>
</Task>
"@
}

# --- status ---------------------------------------------------------------
if ($Status) {
    $missing = 0
    foreach ($component in (Get-Names)) {
        $task = Get-TaskOf (TaskNameOf $component)
        if (-not $task) {
            Write-Host ("{0,-9} not registered" -f $component) -ForegroundColor Yellow
            $missing++
            continue
        }
        $info = Get-ScheduledTaskInfo -TaskName $task.TaskName
        Write-Host ("{0,-9} {1,-8} last run {2} result={3}" -f `
            $component, $task.State, $info.LastRunTime, $info.LastTaskResult) -ForegroundColor Green
    }
    if ($missing -eq 0) { Write-Host "all requested tasks are registered" -ForegroundColor Green }
    exit 0
}

# --- uninstall ------------------------------------------------------------
if ($Uninstall) {
    $dir = Get-LauncherDir
    foreach ($component in (Get-Names)) {
        $taskName = TaskNameOf $component
        $task = Get-TaskOf $taskName
        if ($task) {
            try { Stop-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue } catch { }
            Unregister-ScheduledTask -TaskName $taskName -Confirm:$false
            Write-Host "removed task '$taskName'" -ForegroundColor Green
        } else {
            Write-Host "task '$taskName' is not registered" -ForegroundColor Yellow
        }
        foreach ($ext in @('cmd', 'vbs')) {
            $file = Join-Path $dir ("start-$component.$ext")
            if (Test-Path $file) { Remove-Item $file -Force }
        }
    }
    exit 0
}

# --- register -------------------------------------------------------------
$dir = Get-LauncherDir
New-Item -ItemType Directory -Force -Path $dir | Out-Null

foreach ($component in (Get-Names)) {
    $cmdPath = Make-Cmd $component $dir
    $vbsPath = Make-Vbs $component $cmdPath $dir
    $xml = TaskXml $component $vbsPath
    $null = [xml]$xml          # a malformed document would fail later with a useless message
    $taskName = TaskNameOf $component

    if ($DryRun) {
        Write-Host "dry run: $taskName" -ForegroundColor Yellow
        Write-Host "  cmd     : $cmdPath"
        Write-Host "  vbs     : $vbsPath"
        Write-Host "  python  : $Python"
        Write-Host "  repo    : $root"
        Write-Host "  bus url : $BusUrl"
        continue
    }

    $xmlFile = Join-Path $dir ("task-$component.xml")
    Set-Content -Path $xmlFile -Value $xml -Encoding Unicode
    try {
        $output = & schtasks.exe /Create /TN $taskName /XML $xmlFile /F 2>&1
        if ($LASTEXITCODE -ne 0) {
            $detail = ($output -join ' ').Trim()
            throw "schtasks failed ($LASTEXITCODE) for '$taskName': $detail"
        }
    } finally {
        if (Test-Path $xmlFile) { Remove-Item $xmlFile -Force }
    }
    Write-Host ("registered {0}  ({1})" -f $taskName, $components[$component].Script) -ForegroundColor Green
}

if ($Start -and -not $DryRun) {
    foreach ($component in (Get-Names)) {
        Start-ScheduledTask -TaskName (TaskNameOf $component)
        Write-Host ("started {0}" -f (TaskNameOf $component)) -ForegroundColor Green
    }
}

if (-not $DryRun) {
    Write-Host ""
    Write-Host "inspect : pwsh -File scripts/install-bus-autostart.ps1 -Status"
    Write-Host "logs    : $($dir.TrimEnd('autostart'))logs\bus.log ..."
    Write-Host "remove  : pwsh -File scripts/install-bus-autostart.ps1 -Uninstall -All"
}
