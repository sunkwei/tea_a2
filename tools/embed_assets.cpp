// embed_assets.cpp -- build-time helper that converts web/ assets into a C++
// translation unit, so the tea_agent binary is fully self-contained.
//
// usage: tea_embed_assets <output-dir> <web-dir> <relpath> [<relpath> ...]
//
// The virtual asset name is the relative path exactly as written on the command
// line; the file is read from <web-dir>/<relpath>. The output directory must
// already exist (CMake creates it).
//
// Deliberately depends on nothing but the C standard library plus <string>, so
// it builds with any host compiler including GCC 6.5.

#include <algorithm>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

struct Asset {
  std::string path;  // virtual path, e.g. "app.js"
  std::string mime;
  std::string data;
};

static std::string read_binary(const std::string& full_path) {
  std::ifstream in(full_path.c_str(), std::ios::binary);
  if (!in) {
    std::fprintf(stderr, "embed_assets: cannot open %s\n", full_path.c_str());
    std::exit(2);
  }
  std::ostringstream ss;
  ss << in.rdbuf();
  return ss.str();
}

static std::string mime_for(const std::string& name) {
  struct Pair {
    const char* suffix;
    const char* mime;
  };
  static const Pair kMap[] = {
      {".html", "text/html; charset=utf-8"},
      {".css", "text/css; charset=utf-8"},
      {".js", "text/javascript; charset=utf-8"},
      {".mjs", "text/javascript; charset=utf-8"},
      {".json", "application/json; charset=utf-8"},
      {".svg", "image/svg+xml"},
      {".png", "image/png"},
      {".ico", "image/x-icon"},
      {".woff2", "font/woff2"},
      {".txt", "text/plain; charset=utf-8"},
      {".md", "text/markdown; charset=utf-8"},
  };
  for (const Pair& p : kMap) {
    const size_t n = std::strlen(p.suffix);
    if (name.size() >= n && name.compare(name.size() - n, n, p.suffix) == 0) return p.mime;
  }
  return "application/octet-stream";
}

// Emit a C++ string literal. Uses a raw string literal when safe, otherwise
// falls back to a fully escaped ordinary literal.
//
// A raw literal is only safe when the compiler will hand back exactly the bytes
// we put in: translation phase 1 rewrites CRLF to LF *inside* literals, so a
// raw literal holding CRLF text compiles to fewer bytes than the file. That
// silently broke the Web UI once -- kAssetData_N ended early, the table still
// claimed the on-disk size, and the server read past the terminator into the
// next asset, appending CSS to app.js (a syntax error that killed the page).
// CR-bearing data therefore takes the escaped path, which spells out \r.
static bool raw_literal_is_safe(const std::string& data) {
  static const char* kDelim = "TEA_ASSET_8f3c1d";
  const std::string terminator = std::string(")") + kDelim + "\"";
  if (data.find(terminator) != std::string::npos) return false;
  return data.find('\r') == std::string::npos;
}

static std::string to_literal(const std::string& data) {
  static const char* kDelim = "TEA_ASSET_8f3c1d";
  if (raw_literal_is_safe(data)) {
    return std::string("R\"") + kDelim + "(" + data + ")" + kDelim + "\"";
  }
  std::string out = "\"";
  char buf[16];
  for (size_t i = 0; i < data.size(); ++i) {
    const unsigned char c = static_cast<unsigned char>(data[i]);
    switch (c) {
      case '\\': out += "\\\\"; break;
      case '"': out += "\\\""; break;
      case '\n': out += "\\n"; break;
      case '\r': out += "\\r"; break;
      case '\t': out += "\\t"; break;
      default:
        if (c < 0x20 || c == 0x7f) {
          // Close and reopen the literal so a following hex digit cannot be
          // swallowed by the \x escape.
          std::snprintf(buf, sizeof(buf), "\\x%02x\" \"", c);
          out += buf;
        } else {
          out += static_cast<char>(c);
        }
    }
  }
  out += "\"";
  return out;
}

int main(int argc, char** argv) {
  if (argc < 3) {
    std::fprintf(stderr, "usage: tea_embed_assets <output-dir> <web-dir> <relpath> [relpath...]\n");
    return 2;
  }
  const std::string out_dir = argv[1];
  std::string web_dir = argv[2];
  while (!web_dir.empty() && (web_dir[web_dir.size() - 1] == '/' || web_dir[web_dir.size() - 1] == '\\')) {
    web_dir.erase(web_dir.size() - 1);
  }

  std::vector<Asset> assets;
  for (int i = 3; i < argc; ++i) {
    std::string rel = argv[i];
    for (size_t k = 0; k < rel.size(); ++k) {
      if (rel[k] == '\\') rel[k] = '/';
    }
    Asset a;
    a.path = rel;
    a.mime = mime_for(rel);
    a.data = read_binary(web_dir + "/" + rel);
    assets.push_back(a);
  }
  std::sort(assets.begin(), assets.end(),
            [](const Asset& a, const Asset& b) { return a.path < b.path; });

  {
    const std::string h_path = out_dir + "/web_assets.h";
    std::ofstream h(h_path.c_str(), std::ios::binary);
    if (!h) {
      std::fprintf(stderr, "embed_assets: cannot write %s\n", h_path.c_str());
      return 2;
    }
    h << "// Generated by tools/embed_assets.cpp -- do not edit.\n"
         "#pragma once\n"
         "#include <cstddef>\n\n"
         "namespace tea {\n"
         "struct WebAsset {\n"
         "  const char* path;\n"
         "  const char* mime;\n"
         "  const char* data;\n"
         "  std::size_t size;\n"
         "};\n"
         "extern const WebAsset kWebAssets[];\n"
         "extern const std::size_t kWebAssetCount;\n"
         "}  // namespace tea\n";
  }

  {
    const std::string c_path = out_dir + "/web_assets.cpp";
    std::ofstream c(c_path.c_str(), std::ios::binary);
    if (!c) {
      std::fprintf(stderr, "embed_assets: cannot write %s\n", c_path.c_str());
      return 2;
    }
    c << "// Generated by tools/embed_assets.cpp -- do not edit.\n"
         "#include \"web_assets.h\"\n\n"
         "namespace tea {\n\n";
    for (size_t i = 0; i < assets.size(); ++i) {
      c << "static const char kAssetData_" << i << "[] =\n" << to_literal(assets[i].data) << ";\n";
      // The table below advertises the on-disk size, and the server sends that
      // many bytes. If the compiled array ever ends up shorter (see the CRLF
      // note in to_literal), this fails the build instead of serving garbage.
      c << "static_assert(sizeof(kAssetData_" << i << ") - 1 == " << assets[i].data.size()
        << ", \"embedded asset size mismatch: " << assets[i].path << "\");\n";
    }
    c << "\nconst WebAsset kWebAssets[] = {\n";
    for (size_t i = 0; i < assets.size(); ++i) {
      c << "  {\"" << assets[i].path << "\", \"" << assets[i].mime << "\", kAssetData_" << i
        << ", " << assets[i].data.size() << "},\n";
    }
    c << "};\n\nconst std::size_t kWebAssetCount = sizeof(kWebAssets) / sizeof(kWebAssets[0]);\n\n"
         "}  // namespace tea\n";
  }

  std::printf("embed_assets: wrote %d assets to %s\n", static_cast<int>(assets.size()),
              out_dir.c_str());
  return 0;
}
